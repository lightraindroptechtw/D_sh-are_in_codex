test('main chat maps actual event payloads, scopes history, sharing switch and current model',async()=>{
  const events=[],requests=[];
  const bridge=createConversationBridge({emit:async(name,...args)=>events.push([name,...args]),requestHost:async(method,params)=>{requests.push({method,params});return {queued:true};}});
  assert.deepEqual(bridge.selection(),{provider:'codex',model:null});
  await bridge.event({sessionId:'main',kind:'model',model:'gpt-6.1-sol',allowFollowups:true});
  await bridge.event({sessionId:'main',kind:'user',text:'hello'});
  assert.equal(bridge.agent.status,'running');
  await bridge.event({sessionId:'main',kind:'tool-call',callId:'c1',name:'shell',input:{command:'pwd'}});
  await bridge.event({sessionId:'main',kind:'tool-result',callId:'c1',name:'shell',text:'workspace'});
  await bridge.event({sessionId:'main',kind:'turn-end',answer:'done',reason:'answer'});
  assert.equal(bridge.agent.status,'idle');assert.equal(bridge.agent.lastReply,'done');
  const history=await bridge.query.readSession('main');
  assert.deepEqual(history.events.map(e=>e.type),['turn/start','user/message','tool/call','tool/result','assistant/message','turn/end']);
  assert.equal(history.events[2].data.arguments,'{"command":"pwd"}');
  assert.equal(history.events[3].data.message.toolCallId,'c1');
  assert.equal(history.events[4].data.message.source.model,'gpt-6.1-sol');
  await assert.rejects(bridge.event({sessionId:'other',kind:'model',model:'wrong'}),{code:'CODEX_CONVERSATION_SCOPE'});
  assert.equal(bridge.selection().model,'gpt-6.1-sol');
  await assert.rejects(bridge.query.readSession('other'),{code:'CODEX_SESSION_SCOPE'});
  await bridge.event({sessionId:'main',kind:'user',text:'private',shareConversation:false});
  assert.deepEqual(await bridge.query.listSessions(),[]);
  await assert.rejects(bridge.query.readSession('main'),{code:'DSH_CONVERSATION_SHARING_DISABLED'});
  await bridge.event({sessionId:'main',kind:'model',model:'gpt-6-luna',shareConversation:false});
  assert.equal(bridge.selection().model,'gpt-6-luna');
  bridge.agent.followup('follow up');await bridge.flush();
  assert.equal(requests[0].method,'codex.conversation.followup');assert.equal(requests[0].params.sessionId,'main');
  await bridge.event({sessionId:'main',kind:'model',shareConversation:true});
  assert.equal((await bridge.query.readSession('main')).events.length,6);
  const combined=includeConversationAgent({list:()=>[{id:'child'}],get:id=>({id})},bridge);
  assert.deepEqual(combined.list().map(x=>x.id),['codex-main-conversation','child']);
  assert.equal(combined.get('codex-main-conversation'),bridge.agent);
  await bridge.dispose();
});

test('worker loads an unmodified DSH listener and all four main-conversation interfaces',async t=>{
  const root=await mkdtemp(path.join(tmpdir(),'codex-main-bridge-')),sourceRoot=path.join(root,'source');await mkdir(sourceRoot);
  let host,client;t.after(async()=>{await client?.close();await host?.dispose();await rm(root,{recursive:true,force:true});});
  await writeFile(path.join(sourceRoot,'package.json'),'{"type":"module"}');
  await writeFile(path.join(sourceRoot,'index.js'),`import {defineTool} from '@deepseek-ai/dsh-tools';
    export const name='main-chat-probe';export const inject=['tools','sessionQuery','agentDefaultModel'];
    export function apply(ctx){const seen=[],agents=[];ctx.on('session/event',(_,e)=>seen.push(e.type));ctx.on('agent/created',({agent})=>agents.push(agent));
    ctx.on('session/event',(_,e)=>{if(e.type==='turn/end')agents[0].followup('next task');});
    ctx.tools.register(defineTool({name:'state',description:'state',parameters:{},output:{schema:{type:'json'},render:(_,v)=>[{type:'text',text:JSON.stringify(v)}]},execute:async()=>({seen,agents:agents.map(a=>a.id),history:await ctx.sessionQuery.listSessions(),model:ctx.agentDefaultModel.currentSelection()})}));}`);
  const requests=[];host=await loadDshHost({entry:path.join(sourceRoot,'index.js'),sourceRoot,stateDir:path.join(root,'state'),runtimeRoot:fileURLToPath(new URL('../',import.meta.url)),services:[],plan:{host:{services:['sessionQuery','agentDefaultModel']}},bridgeRequest:async(method,params)=>{requests.push({method,params});return {queued:true};}});
  const first=await host.request('conversation.event',{sessionId:'main-1',kind:'model',model:'gpt-6.1-sol',shareConversation:true,allowFollowups:true});
  assert.equal(first.listeners.sessionEvent,2);assert.equal(first.listeners.agentCreated,1);
  await host.request('conversation.event',{sessionId:'main-1',kind:'user',text:'hello'});
  await host.request('conversation.event',{sessionId:'main-1',kind:'turn-end',answer:'finished',reason:'answer'});
  assert.equal(requests[0].method,'codex.conversation.followup');assert.equal(requests[0].params.text,'next task');
  const state=JSON.parse((await host.tools[0].execute({})).content[0].text);
  assert.deepEqual(state.seen,['turn/start','user/message','assistant/message','turn/end']);
  assert.deepEqual(state.agents,['codex-main-conversation']);assert.equal(state.history[0].header.id,'main-1');assert.equal(state.model.model,'gpt-6.1-sol');
  await host.dispose();host=null;
  // Exercise the generated JS bundles and command hook, not just source imports.
  const generated=path.join(root,'generated');
  await buildOfficialHost({converterRoot:fileURLToPath(new URL('../',import.meta.url)),outputDir:generated,plan:{name:'main-chat-probe',entry:'index.js',source:{origin:sourceRoot},host:{services:['sessionQuery','agentDefaultModel']}},config:{},hooks:true,options:{services:[],stateMode:'package',securitySettings:{shareConversation:true,allowFollowups:true},codexCommand:'dsh-test-no-codex-executable',conversationHistory:false}});
  await cp(sourceRoot,path.join(generated,'source'),{recursive:true});
  client=new McpClient({command:process.execPath,args:[path.join(generated,'runtime/server.mjs')]},{cwd:generated,timeout:30000});await client.start();
  const hook=async(event,extra={})=>{
    const child=spawn(process.execPath,[path.join(generated,'runtime/codex-hook.mjs')],{cwd:generated,windowsHide:true,stdio:['pipe','pipe','pipe']});let raw='',err='';
    child.stdout.on('data',v=>raw+=v);child.stderr.on('data',v=>err+=v);
    child.stdin.end(JSON.stringify({hook_event_name:event,session_id:'generated-main',turn_id:'turn-1',cwd:generated,model:'gpt-6-luna',...extra}));
    const code=await new Promise(resolve=>child.once('exit',resolve));assert.equal(code,0,err);return JSON.parse(raw);
  };
  await hook('UserPromptSubmit',{prompt:'generated user'});
  const result=await hook('Stop',{last_assistant_message:'generated answer'});
  assert.equal(result.decision,'block');assert.equal(result.reason,'插件「main-chat-probe」主動送出的訊息：\nnext task');
  const generatedResult=await client.request('tools/call',{name:'state',arguments:{}});
  assert.notEqual(generatedResult.isError,true,JSON.stringify(generatedResult));
  const generatedState=JSON.parse(generatedResult.content[0].text);
  assert.deepEqual(generatedState.seen,['turn/start','user/message','assistant/message','turn/end']);
  assert.equal(generatedState.model.model,'gpt-6-luna');assert.equal(generatedState.history[0].header.id,'generated-main');
});
